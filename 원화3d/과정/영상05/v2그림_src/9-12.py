"""9-12 손목뼈 여덟 개: 위 = 손바닥 쪽에서 본 손목(두 줄로 맞물린 각진 조각 8 + 손허리뼈 · 노뼈 · 자뼈 그루터기),
아래 = 같은 조각을 하나씩 떼어 놓음(모양 이름: 평행변 없음 · 두 변 평행 · 큰 · 갈고리 · 배 · 반달 · 쐐기 · 완두콩)."""
import sys, os, math; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _블록 as B
from mathutils import Vector
B.scene(line=1.8)
C = [(0.95, 0.80, 0.62), (0.80, 0.88, 0.95), (0.95, 0.90, 0.70), (0.85, 0.80, 0.95)]

def prism(xz, t0, t1, bev=0.06):
    """앞(-y) 윤곽 xz 를 두께 t0~t1 로 밀어낸 조각(모서리 살짝 깎음)."""
    c = Vector((sum(p[0] for p in xz) / len(xz), sum(p[1] for p in xz) / len(xz)))
    sh = lambda p, k: (c.x + (p[0] - c.x) * k, c.y + (p[1] - c.y) * k)
    pts = [(x, t0, z) for x, z in (sh(p, 1 - bev) for p in xz)] + [(x, t1, z) for x, z in (sh(p, 1 - bev) for p in xz)] + \
          [(x, (t0 + t1) / 2, z) for x, z in xz]
    return pts

# 손바닥 쪽에서 본 자리(x 오른 = 엄지 쪽 · z 위 = 손가락 쪽). 아랫줄(팔 쪽) 넷, 윗줄(손 쪽) 넷.
BONES = [
    ("배", [(0.35, -0.55), (1.05, -0.35), (1.25, 0.05), (0.85, 0.2), (0.35, 0.0)], (-0.35, 0.3)),
    ("반달", [(-0.45, -0.6), (0.3, -0.55), (0.3, 0.0), (-0.2, 0.15), (-0.5, -0.15)], (-0.3, 0.32)),
    ("쐐기", [(-1.15, -0.4), (-0.55, -0.6), (-0.5, 0.15), (-0.95, 0.1)], (-0.3, 0.3)),
    ("완두콩", [(-1.2, -0.35), (-0.85, -0.45), (-0.75, -0.05), (-1.1, 0.05)], (-0.6, -0.25)),
    ("평행변 없음", [(0.9, 0.25), (1.35, 0.2), (1.45, 0.75), (0.95, 0.85)], (-0.3, 0.3)),
    ("두 변 평행", [(0.45, 0.25), (0.9, 0.25), (0.92, 0.82), (0.45, 0.75)], (-0.3, 0.25)),
    ("큰", [(-0.1, 0.18), (0.42, 0.22), (0.42, 0.95), (0.05, 1.05), (-0.25, 0.7)], (-0.4, 0.35)),
    ("갈고리", [(-0.95, 0.15), (-0.12, 0.2), (-0.28, 0.72), (-0.7, 0.95), (-1.0, 0.6)], (-0.35, 0.3)),
]

def bone(k, loc, rot=(0, 0, 0), scale=1.0, center=False):
    nm, xz, (t0, t1) = BONES[k]
    c = Vector((sum(p[0] for p in xz) / len(xz), 0, sum(p[1] for p in xz) / len(xz))) if center else Vector()
    g = B.empty(loc=loc, rot=rot, scale=(scale,) * 3)
    sub = B.empty(loc=tuple(-c), parent=g)
    B.hull(prism(xz, t0, t1), nm, C[k % 4], sub)
    if nm == "갈고리":   # 손바닥 쪽으로 튀어나온 고리
        B.hull([(-0.55, t0, 0.35), (-0.3, t0, 0.35), (-0.42, t0 - 0.45, 0.45), (-0.5, t0 - 0.42, 0.62), (-0.35, t0, 0.6)], "고리", C[k % 4], sub)
    return g

S = 1.9; top = B.empty(loc=(0, 0, 0.9), scale=(S, S, S), rot=(-15, 0, 0))
for k in range(8): bone(k, (0, 0, 0)).parent = top
for x, w in ((1.15, 0.36), (0.7, 0.34), (0.15, 0.36), (-0.4, 0.32), (-0.85, 0.3)):   # 손허리뼈 그루터기
    B.hull(B.tbox(0.0, 0.75, w, 0.4, w * 0.8, 0.32, x0=x, x1=x * 1.12), "손허리", (0.9, 0.9, 0.9), top, loc=(0, 0, 0.9 + (0 if x != 1.15 else -0.12)))
B.hull(B.tbox(-1.1, -0.62, 1.35, 0.6, 1.25, 0.6, x0=0.55, x1=0.6), "노뼈", (0.9, 0.9, 0.9), top)
B.hull(B.tbox(-1.1, -0.62, 0.45, 0.45, 0.42, 0.45, x0=-0.85, x1=-0.85), "자뼈", (0.9, 0.9, 0.9), top)
for k in range(8):
    x = (k - 3.5) * 1.75
