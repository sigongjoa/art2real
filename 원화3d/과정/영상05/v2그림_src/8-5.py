import sys, os; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _블록 as B, _머리 as M
B.scene()
# 개: 머리뼈 상자 + 긴 주둥이 상자 + 아래턱 쐐기 + 귀 + 뒤로 가는 목
d = B.empty(loc=(-3.3, 0, 0.2), rot=(-8, 0, -68))
B.hull(B.cbox(-0.72, 0.72, -0.35, 1.15, -0.55, 0.62, c=0.22), "머리뼈", parent=d)
B.hull(B.tbox(0, 0, 0, 0, 0, 0) and [(sx * w, y, z) for sx in (-1, 1) for (w, y, z) in
       ((0.5, -0.30, 0.38), (0.5, -0.30, -0.45), (0.3, -1.75, 0.05), (0.3, -1.75, -0.38))], "주둥이", parent=d)
B.hull([(sx * w, y, z) for sx in (-1, 1) for (w, y, z) in ((0.45, 0.4, -0.5), (0.25, -1.5, -0.42), (0.22, -1.4, -0.62), (0.4, 0.2, -0.85))], "아래턱", parent=d)
B.hull(B.cbox(-0.17, 0.17, -1.86, -1.70, -0.22, 0.10, c=0.04), "코", B.DARK, parent=d)
for s in (-1, 1):
    B.hull([(s * 0.55, 0.55, 0.55), (s * 0.75, 0.95, 0.55), (s * 0.70, 0.75, 1.1), (s * 0.45, 0.70, 0.55)], "귀", parent=d)
B.hull([(sx * w, y, z) for sx in (-1, 1) for (w, y, z) in ((0.5, 0.4, -0.35), (0.5, 1.0, 0.35), (0.55, 2.2, -0.15), (0.55, 1.5, -1.15))], "목", parent=d)
B.rod((-5.5, -3, 0.05), (-1.0, -3, 0.05))                      # 긴 축: 수평
# 사람: 같은 상자 머리, 축은 수직
h = B.empty(loc=(3.0, 0, 0.1), rot=(-8, 0, -68)); M.head(h)
