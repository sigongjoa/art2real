def plen(p):
    return sum(math.dist(p[i], p[i + 1]) for i in range(len(p) - 1))


def load(f, c):
    im = Image.open(os.path.join(R, f)).convert('RGB')
    if c:
        im = im.crop(c)
    s = 900 / im.height
    return im.resize((round(im.width * s), 900), Image.LANCZOS)


def ratios(d):
    f, c, top, sole, m = d
    H = sole - top
    return {k: sum(plen(p) for p in v) / len(v) / H for k, v in m.items()}


rat = {k: ratios(v) for k, v in SRC.items()}
side = {k: ratios(v) for k, v in SIDE.items()}
table = {}
for m in MEAS:
    ov = [rat[o][m] for o in ORIG if m in rat[o]]
    om = sum(ov) / len(ov)
    row = {'원작': [round(x, 4) for x in ov], '원작평균': round(om, 4),
           '원작범위%': [round((min(ov) / om - 1) * 100, 1), round((max(ov) / om - 1) * 100, 1)]}
    for k in KITS:
        row[k] = round(rat[k][m], 4)
        row[k + '%'] = round((rat[k][m] / om - 1) * 100, 1)
    row['분류'], row['근거'] = WHY[m]
    table[m] = row

# 자체 확인: 원작 셋이 서로 ±25 % 안이어야 읽기 실수가 아니다(넘으면 그 칸은 믿지 않는다)
