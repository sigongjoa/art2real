def 관(링겉, 링속):
    """두 겹 관: 링겉[k], 링속[k] = (n, 3) 링(아래→위). 바깥 · 안 · 위 · 아래 테를 이어 닫힌 메시(오목 단면 그대로 · hull 안 씀)."""
    K, n = len(링겉), len(링겉[0]); V = np.vstack(list(링겉) + list(링속)); F = []
    o = lambda k, i: k * n + i % n; q = lambda k, i: K * n + k * n + i % n
    for k in range(K - 1):
        for i in range(n):
            F += [(o(k, i), o(k, i + 1), o(k + 1, i + 1)), (o(k, i), o(k + 1, i + 1), o(k + 1, i))]
            F += [(q(k, i), q(k + 1, i + 1), q(k, i + 1)), (q(k, i), q(k + 1, i), q(k + 1, i + 1))]
    for i in range(n):
        F += [(o(0, i), q(0, i + 1), o(0, i + 1)), (o(0, i), q(0, i), q(0, i + 1))]
        F += [(o(K - 1, i), o(K - 1, i + 1), q(K - 1, i + 1)), (o(K - 1, i), q(K - 1, i + 1), q(K - 1, i))]
    F = np.array(F, np.uint32)
    m = M.Manifold(M.Mesh(vert_properties=V.astype(np.float32), tri_verts=F))
    if m.volume() < 0 or m.is_empty(): m = M.Manifold(M.Mesh(vert_properties=V.astype(np.float32), tri_verts=F[:, ::-1].copy()))
    assert m.volume() > 1, "관 안 닫힘"
    return m

