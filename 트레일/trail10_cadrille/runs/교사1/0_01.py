import cadquery as cq
def prof(y, out, inn):   # out/inn: 오른쪽 반 (x,z) 바닥→위. 좌우 대칭으로 닫힌 선
    O = [(-x, z) for x, z in out[::-1]] + [(x, z) for x, z in out[1:]]
    I = [(x, z) for x, z in inn[::-1]] + [(-x, z) for x, z in inn[1:]]
    P = lambda q: cq.Vector(q[0], y, q[1])
    e = [cq.Edge.makeSpline([P(q) for q in O]), cq.Edge.makeLine(P(O[-1]), P(I[0])), cq.Edge.makeSpline([P(q) for q in I]), cq.Edge.makeLine(P(I[-1]), P(O[0]))]
    return cq.Wire.assembleEdges(e)
