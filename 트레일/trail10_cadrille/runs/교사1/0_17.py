r = r.union(cq.Workplane('XY', origin=(0, 19, 5)).circle(24).extrude(20))
r = r.union(cq.Workplane('XY').sphere(30).translate((0, 19, 43)).intersect(cq.Workplane('XY').box(80, 80, 59.4).translate((0, 19, 43))))
path = cq.Workplane('XY').spline([(-35, -60, -40), (-48, -40, -22), (-68, 17, -17), (0, 77, -8), (68, 17, -17), (48, -40, -22), (35, -60, -40)], includeCurrent=False)
hose = cq.Workplane('XY').add(cq.Solid.makeSphere(1)).newObject([]).add(path.val())
prof = cq.Wire.makeCircle(10, cq.Vector(-35, -60, -40), path.val().tangentAt(0))
hose = cq.Workplane('XY').add(cq.Solid.sweep(prof, [], path.val(), isFrenet=True))
r = r.union(hose)
