import cadquery as cq
foot = cq.Workplane('XY', origin=(0, 0, -73.6)).polyline([(-40, -100), (40, -100), (65, -90), (65, -5), (76, 0), (76, 90), (-76, 90), (-76, 0), (-65, -5), (-65, -90)]).close()
flange = foot.extrude(12.6)
side = cq.Workplane('YZ').polyline([(-100, -74), (99, -74), (92, -61), (85, -61), (77, -25), (66, -15), (52, 10), (35, 14), (0, 12), (-26, 2), (-40, -15), (-62, -29), (-70, -40), (-82, -52), (-86, -61), (-91, -61), (-100, -74)]).close().extrude(90, both=True)
