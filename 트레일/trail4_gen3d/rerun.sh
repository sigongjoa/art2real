#!/bin/sh
# 깊이 보정 메시로 분할·UV·굽기 전체 재실행
B="C:/Program Files/Blender Foundation/Blender 4.0/blender.exe"
set -e
echo "=== 1/6 재질 투영 ==="
"$B" -b --python project_parts.py -- out/depthfit.blend out/f3_parts.blend 2>&1 | grep -E "광선검사|확산|파츠|armor|dark|gold"
echo "=== 2/6 능선 스냅 ==="
SNAP_BAND=8 "$B" -b --python snap_creases.py -- out/f3_parts.blend out/f3_parts2.blend 2>&1 | grep -E "씨앗|파츠|경계"
echo "=== 3/6 이름 배정 ==="
"$B" -b --python assign_named.py -- out/f3_parts2.blend out/f3_named.blend 2>&1 | grep -E "맞춤|최근접|배정된"
echo "=== 4/6 경계 스냅 ==="
SNAP_BAND=8 "$B" -b --python snap_creases.py -- out/f3_named.blend out/f3_named2.blend 2>&1 | grep -E "파츠|경계"
echo "=== 5/6 UV ==="
UV_PRESMOOTH=10 "$B" -b --python make_uv2.py -- out/f3_named2.blend out/f3_uv.blend 2>&1 | grep -E "언랩|섬 합계|채택"
"$B" -b --python repack_atlas.py -- out/f3_uv.blend out/f3_atlas.blend 2>&1 | grep -E "^\[|합침"
echo "=== 6/6 굽기 ==="
"$B" -b --python bake_art.py -- out/f3_atlas.blend out/f3_baked 2>&1 | grep -E "다음 판|판 배정|래스터화|SAVED"
"$B" -b --python shot_baked.py -- out/f3_baked.blend out/f3bk 2>&1 | grep -E "BAKESHOT"
"$B" -b --python shot_side.py -- out/f3_baked.blend out/f3sd 2>&1 | grep -E "SIDESHOT"
echo "=== DONE ==="
